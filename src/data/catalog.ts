function listed(input: {
  slug: string;
  name: string;
  price: number;
  stock: number;
  brand: string;
  category: string;
  seller: Product["seller"];
  rating: number;
  reviewCount: number;
  image: string;
  alt: string;
  tone: string;
  description: string;
  spec: [string, string];
  review: Product["reviews"][number];
  createdAt: string;
}): Product {
  return {
    slug: input.slug,
    name: input.name,
    price: input.price,
    stock: input.stock,
    brand: input.brand,
    category: input.category,
    seller: input.seller,
    rating: input.rating,
    reviewCount: input.reviewCount,
    images: [{ src: input.image, alt: input.alt }],
    tone: input.tone,
    description: input.description,
    specs: [{ label: input.spec[0], value: input.spec[1] }],
    reviews: [input.review],
    createdAt: input.createdAt,
  };
}

export function getProduct(slug: string) {
  return products.find((product) => product.slug === slug);
}

export function visibleReviews(product: Product) {
  return product.reviews.filter((review) => !review.hidden);
}
